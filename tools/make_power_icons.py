"""Generates src/power_icons.h: the icons of the power menu (long press on Lock PC).

Simple line icons drawn with Pillow at 4x and scaled down, stored as one
alpha byte per pixel. The firmware blends a colour over the background with it.

    python tools/make_power_icons.py
"""
import math
from pathlib import Path

from PIL import Image, ImageDraw

SIZE = 30
OUT = Path(__file__).resolve().parents[1] / "src" / "power_icons.h"


def icon_mask(kind: str, size: int = SIZE) -> Image.Image:
    k = 4
    s = size * k
    stroke = max(2.0, size / 9)
    m = Image.new("L", (s, s), 0)
    d = ImageDraw.Draw(m)
    sw = int(stroke * k)
    pad = sw // 2 + k
    if kind == "power":
        box = (pad, pad + int(s * 0.06), s - pad, s - pad + int(s * 0.06) - k)
        d.arc(box, start=-60, end=240, fill=255, width=sw)
        d.line((s // 2, pad - k, s // 2, s // 2), fill=255, width=sw)
        d.ellipse((s // 2 - sw // 2, pad - k - sw // 2, s // 2 + sw // 2, pad - k + sw // 2), fill=255)
        d.ellipse((s // 2 - sw // 2, s // 2 - sw // 2, s // 2 + sw // 2, s // 2 + sw // 2), fill=255)
    elif kind == "restart":
        d.arc((pad, pad, s - pad, s - pad), start=-50, end=250, fill=255, width=sw)
        r = (s - 2 * pad) / 2 - sw / 2
        a = math.radians(-50)
        ex, ey = s / 2 + r * math.cos(a), s / 2 + r * math.sin(a)
        length = sw * 2.4
        d.polygon([(ex + length * 0.9, ey - length * 0.15),
                   (ex - length * 0.55, ey - length * 0.75),
                   (ex - length * 0.1, ey + length * 0.95)], fill=255)
    elif kind == "sleep":
        d.ellipse((pad, pad, s - pad, s - pad), fill=255)
        off = int(s * 0.30)
        d.ellipse((pad + off, pad - int(s * 0.12), s - pad + off, s - pad - int(s * 0.12)), fill=0)
    else:
        raise ValueError(kind)
    return m.resize((size, size), Image.LANCZOS)


def main() -> None:
    names = ["power", "restart", "sleep"]
    lines = [
        "// Generated by tools/make_power_icons.py - do not edit by hand.",
        "// One alpha byte per pixel.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        f"constexpr int POWER_ICON_SIZE = {SIZE};",
        "",
    ]
    for name in names:
        data = list(icon_mask(name).tobytes())  # mode L: one byte per pixel
        lines.append(f"const uint8_t POWER_ICON_{name.upper()}[] PROGMEM = {{")
        for i in range(0, len(data), SIZE):
            lines.append("  " + ", ".join(f"0x{v:02x}" for v in data[i:i + SIZE]) + ",")
        lines.append("};")
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
