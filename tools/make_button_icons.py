#!/usr/bin/env python3
"""Convert the button icons in ../icons into src/button_icons.h.

Each icon is trimmed to its visible area (the faint outer glow is cut off),
scaled to fit ICON_BOX x ICON_BOX and stored in full colour as three bytes
per pixel: alpha, RGB565 high byte, RGB565 low byte. The firmware blends
each pixel into the button background (icons in their real colours, 1.2.0).

Requirements: Pillow, and cairosvg for .svg sources.
Usage (from the repository root):  python tools/make_button_icons.py
"""
from __future__ import annotations

import io
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ICON_DIR = ROOT / "icons"
OUTPUT = ROOT / "src" / "button_icons.h"
ICON_BOX = 56
TRIM_ALPHA = 60  # pixels at or below this alpha do not count when trimming

# icon name used in config.json  ->  source file in icons/
SOURCES = {
    "claude": "Claude 01.svg",
    "android_studio": "Android Studio 01.png",
    "proton_vpn": "Proton vpn 01.png",
    "telegram": "Telegram 01.png",
    "powershell": "Powershell 01.png",
    "task_manager": "Monitor 02.png",
    "okam_pro": "O-KAM PRO 01.png",
    "lock": "Lock PC 01.png",
}


def load(path: Path) -> Image.Image:
    if path.suffix.lower() == ".svg":
        import cairosvg

        svg = path.read_text(encoding="utf-8")
        # cairosvg does not understand hsl() fills: use the same colour as hex
        # (hsl(14.8, 63.1%, 59.6%) = #d97757, Claude orange).
        svg = re.sub(r'fill="hsl\([^"]*\)"', 'fill="#d97757"', svg)
        data = cairosvg.svg2png(bytestring=svg.encode("utf-8"), output_width=512, output_height=512)
        return Image.open(io.BytesIO(data)).convert("RGBA")
    return Image.open(path).convert("RGBA")


def convert(name: str, path: Path) -> tuple[int, int, bytes]:
    image = load(path)
    bbox = image.getchannel("A").point(lambda a: 255 if a > TRIM_ALPHA else 0).getbbox()
    if bbox:
        image = image.crop(bbox)
    image.thumbnail((ICON_BOX, ICON_BOX), Image.LANCZOS)
    width, height = image.size
    data = bytearray()
    raw = image.tobytes()  # RGBA, 4 bytes per pixel
    for i in range(0, len(raw), 4):
        r, g, b, a = raw[i], raw[i + 1], raw[i + 2], raw[i + 3]
        color = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data += bytes((a, color >> 8, color & 0xFF))
    return width, height, bytes(data)


def main() -> int:
    lines = [
        "// Generated by tools/make_button_icons.py - do not edit by hand.",
        "// Three bytes per pixel: alpha, RGB565 high byte, RGB565 low byte.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "struct ButtonIcon {",
        "  const char *name;",
        "  uint8_t width;",
        "  uint8_t height;",
        "  const uint8_t *data;",
        "};",
        "",
    ]
    entries = []
    for name, filename in SOURCES.items():
        path = ICON_DIR / filename
        if not path.exists():
            print(f"missing: {path}", file=sys.stderr)
            return 1
        width, height, data = convert(name, path)
        symbol = f"ICON_{name.upper()}"
        lines.append(f"// {filename}: {width}x{height}")
        lines.append(f"const uint8_t {symbol}[] PROGMEM = {{")
        for start in range(0, len(data), 24):
            chunk = ", ".join(f"0x{byte:02x}" for byte in data[start : start + 24])
            lines.append(f"  {chunk},")
        lines.append("};")
        lines.append("")
        entries.append(f'  {{"{name}", {width}, {height}, {symbol}}},')
        print(f"{name}: {width}x{height} from {filename}")
    lines.append("const ButtonIcon BUTTON_ICONS[] = {")
    lines += entries
    lines.append("};")
    lines.append(f"constexpr size_t BUTTON_ICON_COUNT = {len(entries)};")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
