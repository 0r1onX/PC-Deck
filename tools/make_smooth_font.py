#!/usr/bin/env python3
"""Make src/media_font.h: an anti-aliased font with Greek letters for the
MUSIC page (song title and artist).

The built-in fonts of the display only have ASCII. TFT_eSPI can draw
"smooth" fonts in its .vlw format straight from flash (tft.loadFont(array)),
with any Unicode characters in them. This script renders the glyphs of a
TrueType font with Pillow and writes them as a .vlw byte array.

Characters: ASCII, Latin-1 (accented Latin letters), Greek with tonos and
dialytika, and a few typographic signs (dashes, quotes, ellipsis). The
bridge replaces any other character before it is sent (see
MEDIA_FONT_CHARS in host/control_deck_bridge.py - keep both lists equal).

Default font: DejaVu Sans (free license, https://dejavu-fonts.github.io/License.html).
Requirements: Pillow.
Usage (from the repository root):
    python tools/make_smooth_font.py --ttf path/to/DejaVuSans.ttf [--size 15]
"""
from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src" / "media_font.h"
DEFAULT_TTF = [
    Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"),
    Path.home() / "AppData/Local/Microsoft/Windows/Fonts/DejaVuSans.ttf",
    Path("C:/Windows/Fonts/DejaVuSans.ttf"),
]


def char_codes() -> list[int]:
    codes = list(range(0x21, 0x7F))  # space is drawn by the library itself
    codes += range(0xA1, 0x100)  # Latin-1 (0xA0 = no-break space -> space)
    codes += [0x0384, 0x0385, 0x0386, 0x0388, 0x0389, 0x038A, 0x038C]
    codes += range(0x038E, 0x03A2)
    codes += range(0x03A3, 0x03CF)
    codes += [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026]
    return sorted(set(codes) - {0xAD})  # soft hyphen has no glyph


def render_glyph(font: ImageFont.FreeTypeFont, code: int, size: int):
    """Returns (width, height, x_advance, dY, dX, alpha bytes)."""
    ch = chr(code)
    canvas = Image.new("L", (size * 4, size * 4), 0)
    origin = (size, size * 2)  # left end of the baseline
    ImageDraw.Draw(canvas).text(origin, ch, font=font, fill=255, anchor="ls")
    advance = int(round(font.getlength(ch)))
    box = canvas.getbbox()
    if box is None:
        return 0, 0, advance, 0, 0, b""
    left, top, right, bottom = box
    glyph = canvas.crop(box)
    return (right - left, bottom - top, advance, origin[1] - top, left - origin[0],
            glyph.tobytes())


def build(ttf: Path, size: int) -> bytes:
    font = ImageFont.truetype(str(ttf), size)
    codes = char_codes()
    glyphs = [render_glyph(font, code, size) for code in codes]
    ascent = render_glyph(font, ord("d"), size)[3]
    descent = render_glyph(font, ord("p"), size)[1] - render_glyph(font, ord("p"), size)[3]
    out = bytearray(struct.pack(">6I", len(codes), 11, size, 0, ascent, descent))
    for code, (w, h, adv, dy, dx, _) in zip(codes, glyphs):
        out += struct.pack(">7i", code, h, w, adv, dy, dx, 0)
    for *_, data in glyphs:
        out += data
    name = b"MediaFont"
    out += bytes([len(name)]) + name + b"\x00" + bytes([len(name)]) + name + b"\x00" + b"\x01"
    return bytes(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ttf", type=Path, help="TrueType font with Greek letters")
    parser.add_argument("--size", type=int, default=15, help="font size in pixels (default 15)")
    args = parser.parse_args()
    ttf = args.ttf or next((p for p in DEFAULT_TTF if p.is_file()), None)
    if ttf is None or not ttf.is_file():
        print("DejaVuSans.ttf not found: pass --ttf PATH", file=sys.stderr)
        return 1
    data = build(ttf, args.size)
    lines = [
        "// Generated by tools/make_smooth_font.py - do not edit by hand.",
        f"// {ttf.name}, {args.size} px, anti-aliased, TFT_eSPI .vlw format.",
        "// Glyphs rendered from DejaVu Sans: Copyright (c) 2003 by Bitstream, Inc.",
        "// (Bitstream Vera); DejaVu changes are in the public domain. License:",
        "// https://dejavu-fonts.github.io/License.html",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        f"const uint8_t MEDIA_FONT[{len(data)}] PROGMEM = {{",
    ]
    for start in range(0, len(data), 24):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[start:start + 24]) + ",")
    lines += ["};", ""]
    OUTPUT.write_text("\n".join(lines), encoding="ascii")
    print(f"wrote {OUTPUT} ({len(data)} bytes, {len(char_codes())} glyphs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
