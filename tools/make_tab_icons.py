#!/usr/bin/env python3
"""Convert the footer tab icons in ../icons into src/tab_icons.h.

Each icon is trimmed to its visible area (the faint outer glow is cut off),
scaled to fit ICON_BOX x ICON_BOX and stored in full colour as three bytes
per pixel: alpha, RGB565 high byte, RGB565 low byte. The firmware blends
each pixel into the tab background colour.

Requirements: Pillow.
Usage (from the repository root):  python tools/make_tab_icons.py
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ICON_DIR = ROOT / "icons"
OUTPUT = ROOT / "src" / "tab_icons.h"
ICON_BOX = 26
TRIM_ALPHA = 60  # pixels at or below this alpha do not count when trimming

# Order must match the footer tabs: MONITOR, DISKS, WEATHER, CONTROLS, MUSIC.
SOURCES = [
    ("monitor", "Monitor 01.png"),
    ("disks", "Storage 01.png"),
    ("weather", "Weather 01.png"),
    ("controls", "Deck 01.png"),
    ("music", "Music 01.png"),
]


def convert(path: Path) -> tuple[int, int, bytes]:
    image = Image.open(path).convert("RGBA")
    bbox = image.getchannel("A").point(lambda a: 255 if a > TRIM_ALPHA else 0).getbbox()
    if bbox:
        image = image.crop(bbox)
    image.thumbnail((ICON_BOX, ICON_BOX), Image.LANCZOS)
    width, height = image.size
    data = bytearray()
    raw = image.tobytes()  # RGBA, 4 bytes per pixel
    for i in range(0, len(raw), 4):
        r, g, b, a = raw[i], raw[i + 1], raw[i + 2], raw[i + 3]
        color = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data += bytes((a, color >> 8, color & 0xFF))
    return width, height, bytes(data)


def main() -> int:
    lines = [
        "// Generated by tools/make_tab_icons.py - do not edit by hand.",
        "// Three bytes per pixel: alpha, RGB565 high byte, RGB565 low byte.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "struct TabIcon {",
        "  uint8_t width;",
        "  uint8_t height;",
        "  const uint8_t *data;",
        "};",
        "",
        f"constexpr int TAB_ICON_BOX = {ICON_BOX};",
        "",
    ]
    entries = []
    for name, filename in SOURCES:
        path = ICON_DIR / filename
        if not path.exists():
            print(f"missing: {path}", file=sys.stderr)
            return 1
        width, height, data = convert(path)
        symbol = f"TAB_ICON_{name.upper()}"
        lines.append(f"// {filename}: {width}x{height}")
        lines.append(f"const uint8_t {symbol}[] PROGMEM = {{")
        for start in range(0, len(data), 24):
            chunk = ", ".join(f"0x{byte:02x}" for byte in data[start : start + 24])
            lines.append(f"  {chunk},")
        lines.append("};")
        lines.append("")
        entries.append(f"  {{{width}, {height}, {symbol}}},  // {name}")
        print(f"{name}: {width}x{height} from {filename}")
    lines.append("// Same order as the footer tabs.")
    lines.append("const TabIcon TAB_ICONS[] = {")
    lines += entries
    lines.append("};")
    lines.append(f"constexpr size_t TAB_ICON_COUNT = {len(entries)};")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
